#!/usr/bin/env node

import {
  cp,
  lstat,
  mkdir,
  mkdtemp,
  readFile,
  readdir,
  rm,
  stat,
  writeFile,
} from "node:fs/promises";
import { createHash } from "node:crypto";
import { tmpdir } from "node:os";
import { basename, dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const defaultSource = resolve(scriptDirectory, "..");
const readmeStart = "<!-- nexting-devices:start -->";
const readmeEnd = "<!-- nexting-devices:end -->";
const packageMarker = "// Generated by devices/scripts/export-nexting-devices.mjs";
const forbiddenPathPatterns = [
  /(^|\/)\.env(?:\.|$)/i,
  /(^|\/)(?:secrets?|credentials?|signing)(?:\/|\.|$)/i,
  /\.(?:jks|keystore|mobileprovision|p12|pem|key)$/i,
  new RegExp(`(^|/)(?:App|clients|cloud|infrastructure|${["supa", "base"].join("")})(?:/|$)`),
];
const forbiddenContentPatterns = [
  new RegExp(["hardware", "internal/"].join("-")),
  new RegExp(["CCSession", "Model"].join("")),
  new RegExp(["term", "Id|session", "Id|controlRequest", "Id"].join("")),
  new RegExp(["pinclaw", "odp", "authorized", "peripheral", "uuids"].join("_")),
  new RegExp(["BEGIN ", "(?:RSA |EC |OPENSSH )?", "PRIVATE KEY"].join("")),
  new RegExp(["supa", "base"].join(""), "i"),
];

function parseArguments(argv) {
  const options = { source: defaultSource, publicCheckout: "", check: false };
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === "--source") options.source = resolve(argv[++index] ?? "");
    else if (argument === "--public-checkout") {
      options.publicCheckout = resolve(argv[++index] ?? "");
    } else if (argument === "--check") options.check = true;
    else throw new Error(`unknown argument: ${argument}`);
  }
  if (!options.publicCheckout) {
    throw new Error("usage: export-nexting-devices.mjs --public-checkout <path> [--source <path>] [--check]");
  }
  return options;
}

function portablePath(path) {
  return path.split(sep).join("/");
}

async function exists(path) {
  try {
    await stat(path);
    return true;
  } catch (error) {
    if (error?.code === "ENOENT") return false;
    throw error;
  }
}

async function collectFiles(root, ignoredDirectories) {
  const files = [];
  async function visit(directory) {
    for (const entry of await readdir(directory, { withFileTypes: true })) {
      if (entry.isDirectory() && ignoredDirectories.has(entry.name)) continue;
      const path = join(directory, entry.name);
      const metadata = await lstat(path);
      const name = portablePath(relative(root, path));
      if (metadata.isSymbolicLink()) {
        throw new Error(`symlinks are forbidden in the public export: ${name}`);
      }
      if (metadata.isDirectory()) await visit(path);
      else if (metadata.isFile()) files.push({ path, name });
      else throw new Error(`unsupported filesystem entry: ${name}`);
    }
  }
  await visit(root);
  return files.sort((left, right) => left.name.localeCompare(right.name));
}

function isAllowedSourcePath(name, manifest) {
  return manifest.allowedFiles.includes(name)
    || manifest.optionalStagingFiles.includes(name)
    || manifest.optionalGeneratedFiles.includes(name);
}

async function validateSource(source, manifest) {
  const ignored = new Set(manifest.ignoredDirectories);
  const files = await collectFiles(source, ignored);
  const failures = [];
  for (const file of files) {
    if (!isAllowedSourcePath(file.name, manifest)) {
      failures.push(`${file.name}: not present in the export allowlist`);
    }
    for (const pattern of forbiddenPathPatterns) {
      if (pattern.test(file.name)) failures.push(`${file.name}: forbidden path`);
    }
    const content = await readFile(file.path, "utf8");
    for (const pattern of forbiddenContentPatterns) {
      if (pattern.test(file.name) || pattern.test(content)) {
        failures.push(`${file.name}: matches private-boundary rule ${pattern}`);
      }
    }
  }
  for (const required of manifest.allowedFiles) {
    if (!files.some((file) => file.name === required)) {
      failures.push(`${required}: required allowlisted file is missing`);
    }
  }
  if (failures.length > 0) throw new Error(failures.join("\n"));
  return files;
}

function readmeBlock() {
  return `${readmeStart}

## Build hardware for Nexting

The open hardware protocol, C99 device SDK, Swift and Kotlin host SDKs,
conformance vectors, and reference firmware live in [\`devices/\`](devices/).

- Start with the [Devices SDK overview](devices/README.md).
- Read the [wire protocol](devices/SPEC.md).
- Follow the [0.2 migration guide](devices/docs/migration-0.1-to-0.2.md).

Experimental 0.2 supports extensible device identity, buttons, rotary controls,
displays, haptics, battery reporting, and vendor-defined facts while keeping
approval decisions bounded by the trusted Nexting host.

${readmeEnd}`;
}

function mergeReadme(current) {
  const block = readmeBlock();
  const start = current.indexOf(readmeStart);
  const end = current.indexOf(readmeEnd);
  if (start === -1 && end === -1) {
    return `${current.trimEnd()}\n\n${block}\n`;
  }
  if (start === -1 || end === -1 || end < start) {
    throw new Error("public README contains an incomplete Nexting Devices marker block");
  }
  return `${current.slice(0, start)}${block}${current.slice(end + readmeEnd.length)}`;
}

function rootPackage() {
  return `${packageMarker}
// This root package makes the public host SDK installable directly from
// github.com/Nexting-ai/nexting.

// swift-tools-version: 6.0
import PackageDescription

let package = Package(
    name: "Nexting",
    platforms: [
        .iOS(.v16),
        .macOS(.v13),
    ],
    products: [
        .library(name: "NextingDeviceKit", targets: ["NextingDeviceKit"]),
    ],
    targets: [
        .target(
            name: "NextingDeviceKit",
            path: "devices/sdk/swift/Sources/NextingDeviceKit"
        ),
        .testTarget(
            name: "NextingDeviceKitTests",
            dependencies: ["NextingDeviceKit"],
            path: "devices/sdk/swift/Tests/NextingDeviceKitTests"
        ),
    ]
)
`;
}

async function sha256(path) {
  const data = await readFile(path);
  return createHash("sha256").update(data).digest("hex");
}

async function buildExport(source, output, manifest, files) {
  const devices = join(output, manifest.destination);
  await mkdir(devices, { recursive: true });
  for (const file of files) {
    if (
      manifest.optionalStagingFiles.includes(file.name)
      || manifest.optionalGeneratedFiles.includes(file.name)
    ) continue;
    const destination = join(devices, file.name);
    await mkdir(dirname(destination), { recursive: true });
    await cp(file.path, destination, { errorOnExist: true });
  }
  const exportedFiles = await collectFiles(devices, new Set());
  const sums = [];
  for (const file of exportedFiles) {
    if (file.name === "SHA256SUMS") continue;
    sums.push(`${await sha256(file.path)}  ${file.name}`);
  }
  await writeFile(join(devices, "SHA256SUMS"), `${sums.join("\n")}\n`);
}

async function sameTree(left, right) {
  if (!(await exists(left)) || !(await exists(right))) return false;
  const [leftFiles, rightFiles] = await Promise.all([
    collectFiles(left, new Set()),
    collectFiles(right, new Set()),
  ]);
  if (leftFiles.length !== rightFiles.length) return false;
  for (let index = 0; index < leftFiles.length; index += 1) {
    if (leftFiles[index].name !== rightFiles[index].name) return false;
    if (await sha256(leftFiles[index].path) !== await sha256(rightFiles[index].path)) {
      return false;
    }
  }
  return true;
}

async function assertPublicCheckout(path) {
  if (!(await exists(path))) throw new Error(`public checkout does not exist: ${path}`);
  if (!(await exists(join(path, ".git")))) {
    throw new Error(`public checkout is not a Git worktree: ${path}`);
  }
}

async function desiredRootFiles(publicCheckout, output, manifest, source) {
  const currentReadme = (await exists(join(publicCheckout, "README.md")))
    ? await readFile(join(publicCheckout, "README.md"), "utf8")
    : "# Nexting\n";
  const readme = mergeReadme(currentReadme);
  await writeFile(join(output, "README.md"), readme);
  await writeFile(join(output, "Package.swift"), rootPackage());
  for (const [from, to] of Object.entries(manifest.workflowMappings)) {
    const destination = join(output, to);
    await mkdir(dirname(destination), { recursive: true });
    await cp(join(source, from), destination);
  }
}

async function checkGeneratedRoot(publicCheckout, desired, manifest) {
  for (const path of ["README.md", "Package.swift", ...Object.values(manifest.workflowMappings)]) {
    const current = join(publicCheckout, path);
    const expected = join(desired, path);
    if (!(await exists(current)) || await sha256(current) !== await sha256(expected)) return false;
  }
  return true;
}

async function installExport(publicCheckout, built, manifest) {
  const existingPackage = join(publicCheckout, "Package.swift");
  if (await exists(existingPackage)) {
    const content = await readFile(existingPackage, "utf8");
    if (!content.includes(packageMarker) && content !== rootPackage()) {
      throw new Error("refusing to replace an unrelated public Package.swift");
    }
  }
  const destination = join(publicCheckout, manifest.destination);
  await rm(destination, { recursive: true, force: true });
  await cp(join(built, manifest.destination), destination, { recursive: true });
  for (const path of ["README.md", "Package.swift", ...Object.values(manifest.workflowMappings)]) {
    const from = join(built, path);
    const to = join(publicCheckout, path);
    await mkdir(dirname(to), { recursive: true });
    await cp(from, to, { force: true });
  }
}

export async function exportNextingDevices(options) {
  const source = resolve(options.source);
  const publicCheckout = resolve(options.publicCheckout);
  await assertPublicCheckout(publicCheckout);
  const manifest = JSON.parse(
    await readFile(join(source, "scripts", "export-manifest.json"), "utf8"),
  );
  if (manifest.schemaVersion !== 1 || manifest.destination !== "devices") {
    throw new Error("unsupported or unsafe export manifest");
  }
  const files = await validateSource(source, manifest);
  const temporary = await mkdtemp(join(tmpdir(), "nexting-devices-export-"));
  try {
    await buildExport(source, temporary, manifest, files);
    await desiredRootFiles(publicCheckout, temporary, manifest, source);
    if (options.check) {
      const clean = await sameTree(
        join(temporary, manifest.destination),
        join(publicCheckout, manifest.destination),
      ) && await checkGeneratedRoot(publicCheckout, temporary, manifest);
      if (!clean) throw new Error("public checkout differs from the deterministic export");
      return;
    }
    await installExport(publicCheckout, temporary, manifest);
  } finally {
    await rm(temporary, { recursive: true, force: true });
  }
}

if (resolve(process.argv[1] ?? "") === fileURLToPath(import.meta.url)) {
  try {
    await exportNextingDevices(parseArguments(process.argv.slice(2)));
    console.log("Nexting Devices public export passed");
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  }
}
